    /**
     * The elevations, in the order the interpolators of this library want them:
     * {@code z[i][j]} is the height at {@code (eastings()[i], northings()[j])},
     * so the first index runs east and the second north.
     *
     * @return a new {@code SIZE} by {@code SIZE} array of meters
     */
    public static double[][] elevation() {
        double[][] z = new double[SIZE][SIZE];
        for (int row = 0; row < SIZE; ++row) {
            for (int col = 0; col < SIZE; ++col) {
                z[col][row] = ELEVATION[row * SIZE + col];
            }
        }
        return z;
    }

    /**
     * Distance east of the western edge for each column, meters.
     *
     * @return a new array of length {@link #SIZE}, strictly increasing
     */
    public static double[] eastings() {
        double[] x = new double[SIZE];
        for (int i = 0; i < SIZE; ++i) {
            x[i] = i * STEP_EAST;
        }
        return x;
    }

    /**
     * Distance north of the southern edge for each row, meters.
     *
     * @return a new array of length {@link #SIZE}, strictly increasing
     */
    public static double[] northings() {
        double[] y = new double[SIZE];
        for (int j = 0; j < SIZE; ++j) {
            y[j] = j * STEP_NORTH;
        }
        return y;
    }

    /**
     * The latitude of a grid row.
     *
     * @param row
     *            the row, {@code 0} the southern edge
     * @return degrees north
     */
    public static double latitude(int row) {
        return LAT_SOUTH + (LAT_NORTH - LAT_SOUTH) * row / (SIZE - 1.0);
    }

    /**
     * The longitude of a grid column.
     *
     * @param col
     *            the column, {@code 0} the western edge
     * @return degrees east
     */
    public static double longitude(int col) {
        return LON_WEST + (LON_EAST - LON_WEST) * col / (SIZE - 1.0);
    }
