    /**
     * The magnitudes of the events measured on one scale, in order.
     *
     * @param wanted
     *            the scale to keep, for instance {@link #MOMENT_MAGNITUDE}
     * @return the magnitudes of the matching events
     */
    public static double[] magnitudesOn(String wanted) {
        int count = 0;
        for (int i = 0; i < SCALE.length; ++i) {
            if (SCALE_NAME[SCALE[i]].equals(wanted)) {
                count++;
            }
        }
        double[] out = new double[count];
        int at = 0;
        for (int i = 0; i < SCALE.length; ++i) {
            if (SCALE_NAME[SCALE[i]].equals(wanted)) {
                out[at++] = MAGNITUDE[i];
            }
        }
        return out;
    }

